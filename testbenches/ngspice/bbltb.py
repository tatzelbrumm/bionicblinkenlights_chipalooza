"""Testbench builder and runner for the Bionic Blinkenlights core (ngspice, IHP sg13cmos5l)."""
import os, re, subprocess, numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
SRC = os.path.join(ROOT, 'netlist', 'source', 'bbl.spice')
ENV = dict(os.environ, PDK_ROOT=os.environ.get('PDK_ROOT', '/foss/pdks'), PDK='ihp-sg13cmos5l')
OUT = os.path.join(HERE, 'out')

def corner_libs(corner='tt'):
    m = {'tt': 'mos_tt', 'ss': 'mos_ss', 'ff': 'mos_ff', 'sf': 'mos_sf', 'fs': 'mos_fs'}[corner]
    r = {'tt': 'res_typ', 'ss': 'res_wcs', 'ff': 'res_bcs', 'sf': 'res_typ', 'fs': 'res_typ'}[corner]
    return f".lib cornerMOShv.lib {m}\n.lib cornerMOSlv.lib {m}\n.lib cornerRES.lib {r}\n"

def netlist(dig=0, cbus=(3e-12,) * 4, rsw=2e3, vcpla=None, vcplb=None, corner='tt', temp=27, vdd=3.3,
            include=SRC, dut='bbl_core', ena_t=0.0, extra=''):
    """dig: 24-bit integer (dig_in[23:0]); cbus: capacitance on analog_bus0..3 (on-chip line plus
    external load); vcpla/vcplb: None = not driven (on-chip pull-up), else a voltage or a source spec."""
    s = [f"* bbl testbench (generated by bbltb.py)", corner_libs(corner),
         ".option gmin=1e-15 reltol=1e-3 abstol=1e-14 method=gear",
         f".temp {temp}", f".include {include}",
         f"Vdd vdd 0 pwl 0 0 100u {vdd}", "Vddl vddl 0 pwl 0 0 100u 1.2",
         (f"Vena ena 0 pwl 0 0 {max(ena_t,1e-4)} 0 {max(ena_t,1e-4)+1e-4} 1.2")]
    for i in range(24):
        s.append(f"Vd{i} d{i} 0 pwl 0 0 100u {1.2 if (dig >> i) & 1 else 0}")
    for i, c in enumerate(cbus):
        # harness analog bus switch (on-resistance rsw) between the slot pin and the bus line,
        # whose capacitance (on-chip trunk, pad, and the off-chip load) is cbus
        s.append(f"Rsw{i} bus{i} busx{i} {rsw}")
        s.append(f"Cb{i} busx{i} 0 {c}")
    if vcpla is not None:
        s.append(f"Vcpla vcpla 0 {vcpla}")
    if vcplb is not None:
        s.append(f"Vcplb vcplb 0 {vcplb}")
    ds = ' '.join(f'd{i}' for i in range(24))
    if dut == 'bbl_core':
        s.append(f"X1 vdd 0 vddl 0 ena {ds} bus0 bus1 bus2 bus3 vcpla vcplb bbl_core")
    else:
        s.append(dut)
    s.append(extra)
    return '\n'.join(s) + '\n'

VECS = ['v(x1.out0)', 'v(x1.out1)', 'v(x1.out2)', 'v(x1.out3)',
        'v(x1.vm0)', 'v(x1.vm1)', 'v(x1.vm2)', 'v(x1.vm3)',
        'v(bus0)', 'v(bus1)', 'v(bus2)', 'v(bus3)', 'i(vdd)']

def run(net, name, tstop=4.0, tstep='10u', vecs=VECS, keep=True, retry=True):
    os.makedirs(OUT, exist_ok=True)
    # save: keep only the written vectors in memory (all nodes of the extracted netlist over 4 s need 15 GB)
    ctl = (f".control\nset wr_singlescale\nset wr_vecnames\noption numdgt=7\nsave {' '.join(vecs)}\n"
           f"tran {tstep} {tstop}\nwrdata {name}.dat {' '.join(vecs)}\n.endc\n.end\n")
    sp = os.path.join(OUT, name + '.sp')
    for ext in ('.dat', '.log'):
        if os.path.exists(os.path.join(OUT, name + ext)):
            os.remove(os.path.join(OUT, name + ext))
    open(sp, 'w').write(net + ctl)
    if not os.path.exists(os.path.join(OUT, '.spiceinit')):
        os.symlink(os.path.join(HERE, '.spiceinit'), os.path.join(OUT, '.spiceinit'))
    r = subprocess.run(['ngspice', '-b', name + '.sp'], cwd=OUT, env=ENV, capture_output=True,
                       text=True, timeout=7200)
    open(os.path.join(OUT, name + '.log'), 'w').write(r.stdout + r.stderr)
    if not os.path.exists(os.path.join(OUT, name + '.dat')):
        raise RuntimeError(f"{name}: no output, see {name}.log")
    d = np.genfromtxt(os.path.join(OUT, name + '.dat'), names=True)
    if d['time'][-1] < 0.999 * tstop and retry and tstep == '10u':
        # the transient solver occasionally fails at a spike onset; one retry at half the step
        return run(net, name, tstop, '5u', vecs, keep, retry=False)
    if d['time'][-1] < 0.999 * tstop:
        raise RuntimeError(f"{name}: transient stopped at {d['time'][-1]:.4g} s of {tstop} s, see {name}.log")
    return d

def spikes(t, out, th=1.65, dead=2e-3):
    """Spike times = falling edges of out (out is low while the neuron fires); edges within the
    dead time after a spike (glitches of out during the spike) are not counted."""
    s = out > th
    e = t[np.where(s[:-1] & ~s[1:])[0]]
    keep = []
    for x in e:
        if not keep or x - keep[-1] > dead:
            keep.append(x)
    return np.array(keep)

def rate(sp, t0):
    sp = sp[sp > t0]
    return (len(sp) - 1) / (sp[-1] - sp[0]) if len(sp) > 1 else 0.0

def iavg(d, t0=0.5):
    t = d["time"]; m = t > t0
    return -np.trapezoid(d["ivdd"][m], t[m]) / (t[m][-1] - t[m][0])

def summary(d, t0=0.5):
    t = d['time']
    res = {}
    for k in range(4):
        sp = spikes(t, d[f'vx1out{k}'])
        res[k] = dict(spikes=sp, f=rate(sp, t0))
    return res

def phase_locking(spA, spB, t0=0.5):
    """Ratio of spike counts and the vector strength of B's spikes relative to A's cycle."""
    A = spA[spA > t0]; B = spB[spB > t0]
    if len(A) < 3 or len(B) < 2:
        return dict(ratio=np.nan, vs=np.nan)
    ph = []
    for b in B:
        k = np.searchsorted(A, b) - 1
        if 0 <= k < len(A) - 1:
            ph.append((b - A[k]) / (A[k + 1] - A[k]))
    ph = np.array(ph)
    vs = abs(np.mean(np.exp(2j * np.pi * ph))) if len(ph) else np.nan
    return dict(ratio=len(A) / max(len(B), 1), vs=vs, phases=ph)


