"""Convert the ngspice source netlist(s) to the CDL form KLayout's IHP LVS reads:
X lines of PDK primitives become M (MOSFET) or R (rhigh) lines; everything else is copied.
usage: python3 mkcdl.py out.cdl in1.spice [in2.spice ...] [--slot N shared|pads]
--slot: append a subcircuit slot_<N> (the harness top-cell name) = the chosen variant, with the pad pin
names of slot N (s<N>_an...)."""
import re, sys
MOS = ('sg13_hv_nmos', 'sg13_hv_pmos', 'sg13_lv_nmos', 'sg13_lv_pmos')
args = sys.argv[2:]
slot = None
if '--slot' in args:
    i = args.index('--slot')
    slot = (int(args[i + 1]), args[i + 2])
    args = args[:i]
out = [f'* {sys.argv[1]}: generated by netlist/cdl/mkcdl.py from {" ".join(sys.argv[2:])}']
for f in args:
    for line in open(f):
        t = line.split()
        if t and t[0][0] in 'Xx':
            model = next((w for w in t[1:] if w in MOS or w == 'rhigh'), None)
            if model in MOS:
                line = 'M' + line[1:]
            elif model == 'rhigh':
                line = 'R' + line[1:]
                if ' ps=' not in line:          # the PCell's poly spacing, extracted by the LVS deck
                    line = line.rstrip('\n') + ' ps=0.18u\n'
        out.append(line.rstrip('\n'))
text = '\n'.join(out) + '\n'
if slot:
    n, v = slot
    a = text.index(f'.subckt bbl_slot_{v} ')
    b = text.index(f'.ends bbl_slot_{v}', a) + len(f'.ends bbl_slot_{v}')
    sub = text[a:b].replace(f'bbl_slot_{v}', f'slot_{n}').replace('s1_an', f's{n}_an')
    text += '\n' + sub + '\n'
open(sys.argv[1], 'w').write(text)
